// Translations. The Arabic text is the key (and the Arabic UI); missing keys fall back to it.
// To add a language: add a table like EN and list it in resolve()/tr().

function resolve(setting, systemLocale) {
    if (setting === "ar" || setting === "en") return setting
    return String(systemLocale || "").indexOf("ar") === 0 ? "ar" : "en"
}

function tr(lang, s) {
    if (lang === "ar") return s
    var v = EN[s]
    return v !== undefined ? v : s
}

